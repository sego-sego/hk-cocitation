"""Additive (Hawkes-type) model of citation transfer, fitted by EM.

    E[y_it] = exp(alpha_i + eta_age + lambda_cal) + sum_{b,l} c_bl * N_bl,it

The first term is the article's own (background) citation rate; the second
adds, for every earlier citation from a work in k-bin b that lies in lag
window l, c_bl expected citations per month.  The expected number of extra
citations generated by one citation from bin b is the branching number
    m_b = sum_l |l| c_bl,
which is the empirical counterpart of the transfer h(k) of the theory: a
citation moves value to the cited article in proportion to h(k).

EM: each observed citation is attributed to the background or to one of the
exposure components in proportion to their rates (E-step); the background
is then a Poisson fixed-effects fit to the fractional counts (closed-form
iterative proportional fitting) and each c is a ratio of sums (M-step).
Inference is by bootstrapping articles.
"""
from __future__ import annotations

import numpy as np


class Hawkes:
    def __init__(self, y, comps, unit, age, cal, article_scale=False):
        """article_scale: multiply the excitation of each article by its own
        factor s_i (normalized to exposure-weighted mean 1), so that the bin
        effects are identified from variation within articles."""
        self.article_scale = article_scale
        """comps: array (K, rows) of exposure counts; unit/age/cal: codes."""
        self.y = np.asarray(y, float)
        self.N = np.asarray(comps, float)
        groups = []
        for f in (unit, age, cal):
            _, inv = np.unique(f, return_inverse=True)
            groups.append(inv)
        self.groups = groups
        self.sN = self.N.sum(axis=1)
        self.nu = self.groups[0].max() + 1
        self.s = np.ones(self.nu)

    def fit(self, c0=None, maxit=3000, tol=1e-10, eta0=None, accel=True):
        y, N = self.y, self.N
        K = N.shape[0]
        c = np.full(K, 1e-3) if c0 is None else np.maximum(np.asarray(c0, float), 1e-8)
        if eta0 is None:
            eta = np.log(np.maximum(np.bincount(self.groups[0], weights=y)[self.groups[0]] /
                                    np.bincount(self.groups[0])[self.groups[0]], 1e-6))
            a = [np.zeros(g.max() + 1) for g in self.groups]
            a[0] = np.log(np.maximum(np.bincount(self.groups[0], weights=y) /
                                     np.bincount(self.groups[0]), 1e-9))
        else:
            a = [x.copy() for x in eta0]
        sy = None
        ll_old = -np.inf

        def eta_of(a):
            return sum(a[g][self.groups[g]] for g in range(3))

        u = self.groups[0]

        def em_step(a, c):
            s = self.s
            bg = np.exp(eta_of(a))
            B0 = c @ N
            B = s[u] * B0
            lam = bg + B
            r = y / lam
            ll = float(np.sum(y * np.log(lam) - lam))
            yb = r * bg  # fractional background counts
            a = [x.copy() for x in a]
            for _ in range(2):
                for g, f in enumerate(self.groups):
                    e = np.exp(eta_of(a))
                    num = np.bincount(f, weights=yb, minlength=len(a[g]))
                    den = np.bincount(f, weights=e, minlength=len(a[g]))
                    a[g] += np.log(np.maximum(num, 1e-300) / den)
                for g in (1, 2):
                    m = a[g].mean()
                    a[g] -= m
                    a[0] += m
            sw = s[u]
            c_new = c * (N @ (r * sw)) / np.maximum(N @ sw, 1e-300)
            if self.article_scale:
                num = np.bincount(u, weights=r * B, minlength=self.nu)       # attributed excited counts
                den = np.bincount(u, weights=c_new @ N, minlength=self.nu)    # exposure under new c
                s_new = np.where(den > 0, num / np.maximum(den, 1e-300), 1.0)
                # normalize: exposure-weighted mean of s equals 1 (scale goes into c)
                w = den
                mean_s = np.sum(s_new * w) / max(np.sum(w), 1e-300)
                if mean_s > 0:
                    s_new /= mean_s
                    c_new = c_new * mean_s
                self.s = s_new
            return a, c_new, ll

        for it in range(maxit):
            a1, c1, ll = em_step(a, c)
            if accel and it % 3 == 2:
                # SQUAREM-style extrapolation on c (background re-fitted next step)
                a2, c2, _ = em_step(a1, c1)
                r1, v = c1 - c, (c2 - c1) - (c1 - c)
                if np.dot(v, v) > 0:
                    alpha = -np.sqrt(np.dot(r1, r1) / np.dot(v, v))
                    cx = np.maximum(c - 2 * alpha * r1 + alpha ** 2 * v, 1e-10)
                    llx = self.loglik(a2, cx)
                    if llx > ll:
                        a1, c1 = a2, cx
            a, c = a1, c1
            if abs(ll - ll_old) < tol * abs(ll) and it > 20:
                break
            ll_old = ll
        self.a, self.c = a, c
        self.ll = self.loglik(a, c)
        self.iters = it + 1
        return c

    def loglik(self, a, c):
        eta = sum(a[g][self.groups[g]] for g in range(3))
        lam = np.exp(eta) + self.s[self.groups[0]] * (c @ self.N)
        return float(np.sum(self.y * np.log(lam) - lam))
